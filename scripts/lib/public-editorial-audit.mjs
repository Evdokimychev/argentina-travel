const TECHNICAL_TRACE_PATTERNS = [
  { code: "placeholder", pattern: /\b(?:placeholder|lorem ipsum|undefined|null)\b/i },
  { code: "todo-marker", pattern: /(?:\[\s*todo\s*\]|\btodo\s*:|\btbd\s*:)/i },
  { code: "development-copy", pattern: /(?:в разработке|скоро появится|тестовые данные|демо-?данные)/i },
  {
    code: "ai-disclosure",
    pattern: /(?:generated by ai|written by ai|как (?:языковая )?модель|искусственн(?:ый|ым) интеллект)/i,
  },
];

const NOT_FOUND_PATTERN = /(?:страница|статья|место|тур|экскурсия) не найден[ао]?/i;

export function decodeHtmlEntities(value) {
  return String(value)
    .replace(/&nbsp;|&#160;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&quot;|&#34;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">");
}

export function visibleTextFromHtml(html) {
  return decodeHtmlEntities(
    String(html)
      .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, " ")
      .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, " ")
      .replace(/<svg\b[^>]*>[\s\S]*?<\/svg>/gi, " ")
      .replace(/<!--([\s\S]*?)-->/g, " ")
      .replace(/<[^>]+>/g, " ")
  ).replace(/\s+/g, " ").trim();
}

export function titleFromHtml(html) {
  const match = String(html).match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  return match ? visibleTextFromHtml(match[1]) : "";
}

export function extractSitemapUrls(xml) {
  return [...String(xml).matchAll(/<loc>([^<]+)<\/loc>/gi)].map((match) =>
    decodeHtmlEntities(match[1].trim())
  );
}

export function inspectPublicHtml({ html, status, path, headers = {} }) {
  const errors = [];
  const text = visibleTextFromHtml(html);
  const title = titleFromHtml(html);
  const robots = `${headers["x-robots-tag"] ?? ""} ${
    String(html).match(/<meta[^>]+name=["']robots["'][^>]+content=["']([^"']+)["']/i)?.[1] ?? ""
  }`.toLowerCase();

  if (status < 200 || status >= 300) {
    errors.push({ code: "http-status", detail: `HTTP ${status}` });
  }
  if (!title) errors.push({ code: "missing-title", detail: "У страницы нет title" });
  if (NOT_FOUND_PATTERN.test(title)) {
    errors.push({ code: "not-found-title", detail: title });
  }
  if (/\bnoindex\b/.test(robots)) {
    errors.push({ code: "noindex-in-sitemap", detail: robots.trim() });
  }

  for (const trace of TECHNICAL_TRACE_PATTERNS) {
    const match = text.match(trace.pattern);
    if (!match) continue;
    const index = match.index ?? 0;
    errors.push({
      code: trace.code,
      detail: text.slice(Math.max(0, index - 80), index + match[0].length + 80),
    });
  }

  return { path, status, title, errors };
}

export async function auditPublicEditorial({ baseUrl, concurrency = 12, fetchImpl = fetch }) {
  const base = new URL(baseUrl);
  const protectedLocalPreview = ["127.0.0.1", "localhost", "::1"].includes(base.hostname);
  const sitemapResponse = await fetchImpl(new URL("/sitemap.xml", base));
  if (!sitemapResponse.ok) {
    throw new Error(`Не удалось получить sitemap.xml: HTTP ${sitemapResponse.status}`);
  }

  const sitemapUrls = extractSitemapUrls(await sitemapResponse.text());
  const paths = [...new Set(sitemapUrls.map((value) => {
    const url = new URL(value, base);
    return `${url.pathname}${url.search}`;
  }))];
  const pages = new Array(paths.length);
  let cursor = 0;

  async function worker() {
    while (cursor < paths.length) {
      const index = cursor++;
      const path = paths[index];
      try {
        const response = await fetchImpl(new URL(path, base), { redirect: "manual" });
        const html = await response.text();
        pages[index] = inspectPublicHtml({
          html,
          status: response.status,
          path,
          headers: {
            "x-robots-tag": protectedLocalPreview
              ? ""
              : response.headers.get("x-robots-tag") ?? "",
          },
        });
      } catch (error) {
        pages[index] = {
          path,
          status: 0,
          title: "",
          errors: [{ code: "request-failed", detail: error instanceof Error ? error.message : String(error) }],
        };
      }
    }
  }

  await Promise.all(Array.from({ length: Math.max(1, concurrency) }, () => worker()));
  const errors = pages.flatMap((page) =>
    page.errors.map((error) => ({ path: page.path, ...error }))
  );

  return {
    schemaVersion: 1,
    status: errors.length === 0 ? "passed" : "failed",
    baseUrl: base.origin,
    protectedLocalPreview,
    sitemapUrlCount: sitemapUrls.length,
    uniquePageCount: paths.length,
    checkedAt: new Date().toISOString(),
    summary: { passed: pages.length - new Set(errors.map((item) => item.path)).size, failed: errors.length },
    errors,
  };
}
