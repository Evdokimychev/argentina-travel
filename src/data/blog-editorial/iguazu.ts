function readyIguazu(
  excerpt: string,
  sources: OfficialSource[],
  sections: ReturnType<typeof section>[],
): EditorialOverride {
  return {
    ...editorialArticle([
      ...sections,
      section(
        "Источники и дата проверки",
        p(
          "Проверено 17.07.2026. Накануне и утром перед поездкой откройте страницу парка: уровень воды, погода и технические работы могут менять доступность отдельных маршрутов.",
          sources.map((source) => `* [${source.label}](${source.url})`).join("\n"),
        ),
      ),
    ]),
    excerpt,
    relatedResources: [RICH_HUB, GUIDE],
    dateModified: VERIFIED_AT,
    publicationReady: true,
  };
}

