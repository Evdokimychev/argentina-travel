function readyBa(
  excerpt: string,
  sources: OfficialSource[],
  sections: ReturnType<typeof section>[],
): EditorialOverride {
  return {
    ...editorialArticle([
      ...sections,
      section(
        "Источники и дата проверки",
        p(
          "Проверено 17.07.2026. Перед выходом ещё раз проверьте часы работы, регистрацию, стоимость и транспорт: эти данные меняются быстрее самого маршрута.",
          sources.map((source) => `* [${source.label}](${source.url})`).join("\n"),
        ),
      ),
    ]),
    excerpt,
    relatedResources: [NEIGHBORHOODS, GUIDE_KULTURA, GUIDE_BEZOPASNOST],
    dateModified: VERIFIED_AT,
    publicationReady: true,
  };
}

