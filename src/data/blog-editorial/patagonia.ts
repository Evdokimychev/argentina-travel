function readyPat(
  excerpt: string,
  sources: OfficialSource[],
  sections: ReturnType<typeof section>[],
): EditorialOverride {
  return {
    ...editorialArticle([
      ...sections,
      section(
        "Источники и дата проверки",
        p(
          "Проверено 17.07.2026. Перед выходом сверяйте фактическую погоду, открытие маршрутов и условия выбранного оператора на даты поездки.",
          sources.map((source) => `* [${source.label}](${source.url})`).join("\n"),
        ),
      ),
    ]),
    excerpt,
    dateModified: "2026-07-17",
    publicationReady: true,
  };
}

function quarantinedPat(excerpt: string, publicationBlockReason: string): EditorialOverride {
  return {
    ...editorialArticle([]),
    excerpt,
    dateModified: "2026-07-17",
    publicationReady: false,
    publicationBlockReason,
  };
}

