function readyNw(
  excerpt: string,
  sources: OfficialSource[],
  sections: ReturnType<typeof section>[],
): EditorialOverride {
  return {
    ...editorialArticle([
      ...sections,
      section(
        "Источники и дата проверки",
        p(
          "Проверено 17.07.2026. Перед каждым автомобильным переездом повторно проверьте прогноз, предупреждения и состояние нужного участка дороги; общая схема маршрута не подтверждает его проходимость сегодня.",
          sources.map((source) => `* [${source.label}](${source.url})`).join("\n"),
        ),
      ),
    ]),
    excerpt,
    relatedResources: [GUIDE, SALTA],
    dateModified: VERIFIED_AT,
    publicationReady: true,
  };
}

