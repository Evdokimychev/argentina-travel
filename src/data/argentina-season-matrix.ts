export function getBestDestinationsForMonth(monthIndex: number): SeasonMatrixRow[] {
  return ARGENTINA_SEASON_MATRIX.filter((row) => row.scores[monthIndex] >= 1).sort(
    (a, b) => b.scores[monthIndex] - a.scores[monthIndex],
  );
}

/** Месяц в часовом поясе Буэнос-Айреса (0 = январь). */
export function getBuenosAiresMonthIndex(date: Date = new Date()): number {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: BUENOS_AIRES_TIME_ZONE,
    month: "numeric",
  }).formatToParts(date);
  const month = Number(parts.find((part) => part.type === "month")?.value);
  return Number.isFinite(month) ? month - 1 : date.getMonth();
}

/** @deprecated Prefer getBuenosAiresMonthIndex after client mount for hydration safety */
export function getCurrentMonthIndex(): number {
  return getBuenosAiresMonthIndex();
}
