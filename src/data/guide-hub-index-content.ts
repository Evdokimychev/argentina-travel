function topicItem(slug: string) {
  const topic = GUIDE_TOPICS[slug];
  if (!topic) throw new Error(`Missing guide topic: ${slug}`);
  return {
    slug,
    title: topic.title,
    description: topic.shortDescription,
    href: guideTopicHref(slug),
  };
}

